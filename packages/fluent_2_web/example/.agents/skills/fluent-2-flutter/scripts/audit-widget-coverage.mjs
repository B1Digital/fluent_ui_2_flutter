#!/usr/bin/env node

import { access, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const SKILL_DIR = path.resolve(SCRIPT_DIR, '..');
const REFERENCES_DIR = path.join(SKILL_DIR, 'references');
const COVERAGE_FILE = path.join(REFERENCES_DIR, 'widget-coverage.json');
const MANIFEST_FILE = path.join(REFERENCES_DIR, 'source-manifest.json');
const API_SURFACE_FILE = path.join(REFERENCES_DIR, 'flutter-api-surface.md');
const args = new Set(process.argv.slice(2));

for (const arg of args) {
  if (arg !== '--write-api') fail(`Unknown argument: ${arg}`);
}

function fail(message) {
  process.stderr.write(`ERROR: ${message}\n`);
  process.exit(1);
}

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(target)));
    if (entry.isFile() && entry.name.endsWith('.dart')) files.push(target);
  }
  return files;
}

async function isRepository(directory) {
  try {
    await access(path.join(directory, 'packages/fluent_2_core/lib'));
    await access(path.join(directory, 'packages/fluent_2_web/lib'));
    return true;
  } catch {
    return false;
  }
}

async function findRepository() {
  const starts = [process.cwd(), path.resolve(SKILL_DIR, '../..')];
  const visited = new Set();
  for (const start of starts) {
    let current = path.resolve(start);
    while (!visited.has(current)) {
      visited.add(current);
      if (await isRepository(current)) return current;
      const parent = path.dirname(current);
      if (parent === current) break;
      current = parent;
    }
  }
  return null;
}

function discoverTypes(source, file, repoDir) {
  const types = [];
  const expression =
    /(?:abstract\s+|base\s+|final\s+|sealed\s+)?class\s+(Fluent[A-Za-z0-9_]+)(?:<[^>{}]+>)?\s+extends\s+([A-Za-z0-9_.,<>? ]*(?:Widget|InheritedTheme))\s*\{/g;
  for (const match of source.matchAll(expression)) {
    types.push({
      name: match[1],
      base: match[2].trim(),
      file: path.relative(repoDir, file),
      package: file.includes('/fluent_2_core/')
        ? 'fluent_2_core'
        : file.includes('/fluent_2_mobile/')
          ? 'fluent_2_mobile'
          : 'fluent_2_web',
    });
  }
  return types;
}

function slugFromUrl(url) {
  const match = new URL(url).pathname.match(
    /^\/components\/web\/react\/core\/([^/]+)\/usage\/$/,
  );
  return match?.[1];
}

function renderApiSurface(types) {
  const widgetTypes = types.filter((type) => type.base.endsWith('Widget'));
  const themeTypes = types.filter((type) => type.base.endsWith('InheritedTheme'));
  const renderTable = (values) =>
    values
      .map(
        (value) =>
          `| \`${value.name}\` | \`${value.base}\` | ${value.package} | \`${value.file}\` |`,
      )
      .join('\n');

  return `# Flutter API surface

Generated by \`scripts/audit-widget-coverage.mjs --write-api\`. Do not edit
this file manually. Constructor signatures remain authoritative in the listed
Dart source files.

## Contents

- Widget classes
- Theme wrappers

## Widget classes

| Type | Base | Package | Source |
| --- | --- | --- | --- |
${renderTable(widgetTypes)}

## Theme wrappers

Inherited theme widgets expose subtree-level component styling. Prefer the
complete component theme over low-level renderer changes.

| Type | Base | Package | Source |
| --- | --- | --- | --- |
${renderTable(themeTypes)}
`;
}

function typesFromApiSurface(markdown) {
  const types = [];
  const expression =
    /^\| `(Fluent[A-Za-z0-9_]+)` \| `([^`]*(?:Widget|InheritedTheme))` \| ([^|]+) \| `([^`]+)` \|$/gm;
  for (const match of markdown.matchAll(expression)) {
    types.push({
      name: match[1],
      base: match[2],
      package: match[3].trim(),
      file: match[4],
    });
  }
  return types;
}

try {
  const coverage = JSON.parse(await readFile(COVERAGE_FILE, 'utf8'));
  if (coverage.schemaVersion !== 2) {
    throw new Error(`Expected widget coverage schema 2, found ${coverage.schemaVersion}.`);
  }
  const manifest = JSON.parse(await readFile(MANIFEST_FILE, 'utf8'));
  const repoDir = await findRepository();
  let types;
  if (repoDir !== null) {
    const libDirectories = [
      path.join(repoDir, 'packages/fluent_2_core/lib'),
      path.join(repoDir, 'packages/fluent_2_web/lib'),
      path.join(repoDir, 'packages/fluent_2_mobile/lib'),
    ];
    const dartFiles = (await Promise.all(libDirectories.map(walk))).flat();
    types = [];
    for (const file of dartFiles) {
      types.push(...discoverTypes(await readFile(file, 'utf8'), file, repoDir));
    }
  } else {
    types = typesFromApiSurface(await readFile(API_SURFACE_FILE, 'utf8'));
  }
  types.sort((a, b) => a.name.localeCompare(b.name) || a.file.localeCompare(b.file));

  // Shared plumbing that a barrel happens to re-export but that is not part of
  // the API a consumer should reach for. Dropped here, before every downstream
  // check, so one list keeps it out of the mapping requirement and out of the
  // published surface at once. Named rather than pattern-matched: "internal"
  // is a deliberate decision about a type, not something a path can imply.
  const internalWidgets = coverage.internalWidgets ?? [];
  // Only against real Dart source. The published surface has already had these
  // filtered out, so in snapshot mode "absent" is the expected state, not rot.
  if (repoDir !== null) {
    const discovered = new Set(types.map((type) => type.name));
    const staleInternal = internalWidgets.filter((name) => !discovered.has(name));
    if (staleInternal.length > 0) {
      throw new Error(
        `Internal widget list is stale; these no longer exist: ${staleInternal.join(', ')}.`,
      );
    }
  }
  types = types.filter((type) => !internalWidgets.includes(type.name));

  const officialSlugs = manifest.categories.webCore.map(slugFromUrl);
  const mappedSlugs = coverage.officialWebCore.map((entry) => entry.slug);
  const missingSlugs = officialSlugs.filter((slug) => !mappedSlugs.includes(slug));
  const staleSlugs = mappedSlugs.filter((slug) => !officialSlugs.includes(slug));
  if (missingSlugs.length > 0 || staleSlugs.length > 0) {
    throw new Error(
      `Official component mapping drift. Missing: ${missingSlugs.join(', ') || 'none'}. ` +
        `Stale: ${staleSlugs.join(', ') || 'none'}.`,
    );
  }

  const mappedWidgets = new Set(
    [...coverage.officialWebCore, ...coverage.repositoryExtensions].flatMap(
      (entry) => entry.widgets,
    ),
  );
  const widgetTypes = types
    .filter((type) => type.base.endsWith('Widget'))
    .map((type) => type.name);
  const missingWidgets = widgetTypes.filter((name) => !mappedWidgets.has(name));
  const unknownWidgets = [...mappedWidgets].filter(
    (name) => !widgetTypes.includes(name),
  );
  if (missingWidgets.length > 0 || unknownWidgets.length > 0) {
    throw new Error(
      `Flutter widget mapping drift. Missing: ${missingWidgets.join(', ') || 'none'}. ` +
        `Unknown: ${unknownWidgets.join(', ') || 'none'}.`,
    );
  }
  const knownThemes = new Set(
    types.filter((type) => type.base.endsWith('InheritedTheme')).map((type) => type.name),
  );
  const mappedThemes = coverage.officialWebCore.flatMap((entry) => entry.themes ?? []);
  const unknownThemes = mappedThemes.filter((name) => !knownThemes.has(name));
  if (unknownThemes.length > 0) {
    throw new Error(`Unknown mapped themes: ${unknownThemes.join(', ')}.`);
  }

  for (const entry of [
    ...coverage.officialWebCore,
    ...coverage.repositoryExtensions,
  ]) {
    const reference = path.join(REFERENCES_DIR, entry.reference);
    await readFile(reference, 'utf8');
  }

  const apiSurface = repoDir === null ? null : renderApiSurface(types);
  if (args.has('--write-api') && repoDir === null) {
    throw new Error('--write-api requires a fluent_2 source checkout.');
  }
  if (args.has('--write-api')) {
    await writeFile(API_SURFACE_FILE, apiSurface);
    process.stdout.write(`Wrote ${API_SURFACE_FILE}\n`);
  } else if (repoDir !== null) {
    const existingApiSurface = await readFile(API_SURFACE_FILE, 'utf8');
    if (existingApiSurface !== apiSurface) {
      throw new Error(
        'The Flutter API surface is stale. Run with --write-api and review the diff.',
      );
    }
  }

  process.stdout.write(
    `officialWebCore=${officialSlugs.length} widgetClasses=${widgetTypes.length} ` +
      `themeWrappers=${types.length - widgetTypes.length} mappedWidgets=${mappedWidgets.size} ` +
      `mode=${repoDir === null ? 'snapshot' : 'checkout'}\n`,
  );
} catch (error) {
  fail(error.message);
}
