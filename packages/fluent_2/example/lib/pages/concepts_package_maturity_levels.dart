    '\n'
    '**Import path:** `@fluentui/react-<name>-preview`\n'
    '\n'
    '**When to use:** When you need early access to new '
    'functionality and can tolerate potential breaking '
    'changes during updates.\n'
    '\n'
    '**💡 Legacy Exemptions:**\n'
    '\n'
    'Some packages don\'t follow the preview naming '
    'convention but are still considered preview status, as '
