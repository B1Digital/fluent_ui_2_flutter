    '`@fluentui/react-calendar-compat`\n'
    '\n'
    '**Import path:** `@fluentui/react-<name>-compat`\n'
    '\n'
    '**When to use:** During migration from v8 to v9 when '
    'native v9 equivalents aren\'t available, or when you '
    'need time to gradually migrate complex implementations.\n'
