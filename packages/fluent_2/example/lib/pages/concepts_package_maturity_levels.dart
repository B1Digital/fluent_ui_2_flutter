    '## Package Categories\n'
    '\n'
    '### 🟢 Stable Packages\n'
    '\n'
    '**Characteristics:**\n'
    '\n'
    '-   Production-ready with stable APIs\n'
    '-   Full support and maintenance\n'
    '-   Version format: `9.x.x`\n'
    '-   Available from `@fluentui/react-components` suite\n'
    '-   Naming convention: `@fluentui/react-<name>`\n'
    '\n'
    '**Examples:** `@fluentui/react-button`, '
    '`@fluentui/react-text`\n'
    '\n'
    '**Import path:** `@fluentui/react-components`\n'
    '\n'
    '**When to use:** For all production applications where '
    'stability and long-term support are important.\n'
    '\n'
    '---\n'
    '\n'
    '### 🟡 Preview Packages\n'
    '\n'
    '**Characteristics:**\n'
    '\n'
    '-   Early access components not yet part of the stable '
    'suite\n'
    '-   May introduce breaking changes\n'
    '-   Active development with intention to become stable\n'
    '-   Version format: `0.x.x` (Note: translates to '
    '`0.major.(minor|patch)`)\n'
    '-   Not available from `@fluentui/react-components` '
    'suite\n'
    '-   Naming convention: `@fluentui/react-<name>-preview` '
